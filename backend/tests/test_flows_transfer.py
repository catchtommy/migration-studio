"""Moving data between databases (db/transfer.py): importing the checkpoints older releases kept in their own SQLite
file, and moving the id generators on after a copy on PostgreSQL and Oracle."""

import sqlite3
from types import SimpleNamespace

import pytest
from sqlalchemy import create_engine, func, select

from app.config import settings
from app.db import transfer
from app.db.migrations import upgrade
from app.db.models import GraphCheckpoint, GraphWrite


def legacy_file(path, with_tables=True, rows=1):
    conn = sqlite3.connect(path)
    if with_tables:
        conn.execute("CREATE TABLE checkpoints (thread_id, checkpoint_ns, checkpoint_id, parent_checkpoint_id, type, "
                     "checkpoint, metadata)")
        conn.execute("CREATE TABLE writes (thread_id, checkpoint_ns, checkpoint_id, task_id, idx, channel, type, value)")
        for i in range(rows):
            conn.execute("INSERT INTO checkpoints VALUES (?, '', ?, NULL, 'msgpack', x'00', x'7b7d')", (f"run-{i}", f"c{i}"))
            conn.execute("INSERT INTO writes VALUES (?, '', ?, 't1', 0, 'chan', 'msgpack', x'01')", (f"run-{i}", f"c{i}"))
    else:
        conn.execute("CREATE TABLE other (x)")
    conn.commit()
    conn.close()


@pytest.fixture
def target(tmp_path, monkeypatch):
    monkeypatch.setattr(settings, "data_dir", tmp_path)
    engine = create_engine(f"sqlite:///{tmp_path}/target.db")
    upgrade(engine)
    yield engine
    engine.dispose()


def _count(engine, model):
    with engine.connect() as c:
        return c.execute(select(func.count()).select_from(model)).scalar()


def test_older_checkpoints_are_imported_once_and_the_file_is_kept_aside(target, tmp_path):
    legacy_file(tmp_path / "checkpoints.db", rows=2)
    (tmp_path / "checkpoints.db-wal").write_text("")
    assert transfer.import_legacy_checkpoints(target) == 2
    assert _count(target, GraphCheckpoint) == 2 and _count(target, GraphWrite) == 2
    with target.connect() as c:
        assert c.execute(select(GraphCheckpoint.checkpoint_ns)).scalars().all() == ["__root__", "__root__"]
    assert not (tmp_path / "checkpoints.db").exists() and (tmp_path / "checkpoints.db.imported").is_file()
    assert not (tmp_path / "checkpoints.db-wal").exists()
    assert transfer.import_legacy_checkpoints(target) == 0  # nothing left to import


def test_an_earlier_imports_file_is_never_overwritten(target, tmp_path):
    (tmp_path / "checkpoints.db.imported").write_text("an earlier import")
    legacy_file(tmp_path / "checkpoints.db", with_tables=False)
    assert transfer.import_legacy_checkpoints(target) == 0  # a file without checkpoints: nothing to bring over
    assert (tmp_path / "checkpoints.db.imported").read_text() == "an earlier import"
    assert (tmp_path / "checkpoints.db.imported.1").is_file()


def test_a_database_that_has_checkpoints_already_imports_none(target, tmp_path):
    legacy_file(tmp_path / "checkpoints.db")
    transfer.import_legacy_checkpoints(target)
    legacy_file(tmp_path / "checkpoints.db", rows=3)
    assert transfer.import_legacy_checkpoints(target) == 0
    assert (tmp_path / "checkpoints.db").is_file()  # left where it is


def test_the_tables_of_a_database_are_detected(tmp_path, target):
    assert transfer.has_tables(target)
    empty = create_engine(f"sqlite:///{tmp_path}/empty.db")
    assert not transfer.has_tables(empty)


@pytest.mark.parametrize("dialect,expected", [("postgresql", "setval(pg_get_serial_sequence"),
                                              ("oracle", "GENERATED BY DEFAULT AS IDENTITY (START WITH LIMIT VALUE)")])
def test_id_generators_move_past_copied_ids(dialect, expected):
    sent = []
    conn = SimpleNamespace(dialect=SimpleNamespace(name=dialect), execute=lambda statement: sent.append(str(statement)))
    transfer._reset_identities(conn)
    assert sent and all(expected in s for s in sent)
    assert any("runs" in s for s in sent) is False  # runs have text ids: nothing to move
    assert any("audit_events" in s for s in sent)
