"""Copying the studio's data between databases (switching from SQLite to PostgreSQL or Oracle, or between servers),
and importing LangGraph checkpoints kept in data/checkpoints.db by earlier versions."""

import logging
import sqlite3
from datetime import timezone

from sqlalchemy import Engine, func, insert, inspect, select, text

from app.config import settings
from app.db.models import Base, GraphCheckpoint, GraphWrite

log = logging.getLogger(__name__)
BATCH = 500


class TargetNotEmpty(RuntimeError):
    def __init__(self, tables: list[str]):
        super().__init__(f"The target database already has data ({', '.join(tables)}). Choose to replace it, or use "
                         "an empty database.")
        self.tables = tables


def _utc(row: dict) -> dict:
    # SQLite gives back naive datetimes; they were written as UTC.
    return {k: v.replace(tzinfo=timezone.utc) if hasattr(v, "tzinfo") and v.tzinfo is None and hasattr(v, "hour")
            else v for k, v in row.items()}


def copy_all(source: Engine, target: Engine, replace: bool = False) -> dict[str, int]:
    """Copy every table from `source` to `target` (both already at the current schema). Returns rows per table."""
    tables = Base.metadata.sorted_tables  # parents before children
    counts = {}
    with source.connect() as src, target.begin() as dst:
        filled = [t.name for t in tables if dst.execute(select(func.count()).select_from(t)).scalar()]
        if filled and not replace:
            raise TargetNotEmpty(filled)
        for table in reversed(tables):
            dst.execute(table.delete())
        for table in tables:
            counts[table.name] = 0
            result = src.execute(select(table)).mappings()
            while batch := result.fetchmany(BATCH):
                dst.execute(insert(table), [_utc(dict(r)) for r in batch])
                counts[table.name] += len(batch)
        _reset_identities(dst)
    return counts


def _reset_identities(conn) -> None:
    """Explicit ids were inserted; move identity generators past them."""
    for table in Base.metadata.sorted_tables:
        column = table.c.get("id")
        if column is None or column.identity is None:
            continue
        if conn.dialect.name == "postgresql":
            conn.execute(text(f"SELECT setval(pg_get_serial_sequence('{table.name}', 'id'), "
                              f"COALESCE(MAX(id), 0) + 1, false) FROM {table.name}"))
        elif conn.dialect.name == "oracle":
            conn.execute(text(f"ALTER TABLE {table.name} MODIFY (id GENERATED BY DEFAULT AS IDENTITY "
                              f"(START WITH LIMIT VALUE))"))


def import_legacy_checkpoints(target: Engine) -> int:
    """Move run checkpoints from data/checkpoints.db (versions before the database could be chosen) into the
    database, once, so paused runs can still be resumed. The file is renamed afterwards."""
    path = settings.data_dir / "checkpoints.db"
    if not path.is_file():
        return 0
    with target.connect() as conn:
        if conn.execute(select(func.count()).select_from(GraphCheckpoint)).scalar():
            return 0
    src = sqlite3.connect(path)
    try:
        if not {"checkpoints", "writes"} <= {r[0] for r in src.execute("SELECT name FROM sqlite_master")}:
            rows = 0
        else:
            rows = _copy_checkpoints(src, target)
    finally:
        src.close()
    kept = path.with_name("checkpoints.db.imported")
    n = 1
    while kept.exists():  # never overwrite an earlier import's file
        kept, n = path.with_name(f"checkpoints.db.imported.{n}"), n + 1
    path.rename(kept)
    for suffix in ("-wal", "-shm"):
        path.with_name(path.name + suffix).unlink(missing_ok=True)
    log.info("Imported %d LangGraph checkpoint(s) from %s", rows, path)
    return rows


def _copy_checkpoints(src: sqlite3.Connection, target: Engine) -> int:
    from app.orchestrator.checkpointer import _ns_in

    with target.begin() as conn:
        cur = src.execute("SELECT thread_id, checkpoint_ns, checkpoint_id, parent_checkpoint_id, type, checkpoint, "
                          "metadata FROM checkpoints")
        rows = 0
        while batch := cur.fetchmany(BATCH):
            conn.execute(insert(GraphCheckpoint), [
                {"thread_id": t, "checkpoint_ns": _ns_in(ns), "checkpoint_id": c, "parent_checkpoint_id": p,
                 "type": ty, "checkpoint": cp, "meta": m} for t, ns, c, p, ty, cp, m in batch])
            rows += len(batch)
        cur = src.execute("SELECT thread_id, checkpoint_ns, checkpoint_id, task_id, idx, channel, type, value "
                          "FROM writes")
        while batch := cur.fetchmany(BATCH):
            conn.execute(insert(GraphWrite), [
                {"thread_id": t, "checkpoint_ns": _ns_in(ns), "checkpoint_id": c, "task_id": task, "idx": i,
                 "channel": ch, "type": ty, "value": v} for t, ns, c, task, i, ch, ty, v in batch])
    return rows


def has_tables(engine: Engine) -> bool:
    return "runs" in inspect(engine).get_table_names()
