"""Placeholder agents that exercise the full orchestration (files, commits, artifacts, gates) without an LLM."""

import time

from app.agents.base_agent import AgentContext, ArtifactOut, StageAgent
from app.config import settings
from app.orchestrator.stages import StageDef

STUB_DELAY = 0.5  # seconds per step, so the UI shows stages progressing


class StubAgent(StageAgent):
    def __init__(self, stage: str):
        self.stage = stage

    def run(self, ctx: AgentContext) -> list[ArtifactOut]:
        stage = ctx.stage_def or StageDef(self.stage, self.stage, "agent", ctx.config.get("description", ""))
        ctx.log(f"[stub] {stage.title}: analysing {ctx.domain}/{ctx.operation}")
        time.sleep(STUB_DELAY)
        if ctx.feedback:
            ctx.log(f"[stub] applying reviewer feedback: {ctx.feedback}")
        answer = None
        if settings.stub_questions:
            answer = ctx.ask(f"[stub] Anything {stage.title} should know about {ctx.operation}?",
                             ["Nothing to add", "See the notes on the domain"])

        out = ctx.output_dir / f"{self.stage}.md"
        lines = [
            f"# {stage.title} — {ctx.domain} / {ctx.operation}",
            "",
            f"_Attempt {ctx.attempt}. Generated by the stub agent; switch this agent to Claude on the Agents page._",
            "",
            "## Purpose",
            stage.description,
        ]
        if ctx.previous_artifacts:
            lines += ["", "## Inputs from earlier steps"]
            lines += [f"- {d.stage_title}: `{d.path}`" + (" (contents included)" if d.content is not None else "")
                      for d in ctx.previous_artifacts]
        guidance = ctx.inputs.as_markdown()
        if guidance:
            lines += ["", "## Inputs received", ""]
            lines += ["#" + line if line.startswith("## ") else line for line in guidance.splitlines()]
        if answer is not None:
            lines += ["", "## Answer received", answer]
        if ctx.feedback:
            lines += ["", "## Reviewer feedback addressed", ctx.feedback]
        out.write_text("\n".join(lines) + "\n")
        artifacts = [ArtifactOut(name=out.name, path=ctx.rel(out), kind="markdown")]
        artifacts += _sample_cross_domain_files(ctx)
        artifacts += _sample_discovery_files(ctx)
        time.sleep(STUB_DELAY)
        ctx.log(f"[stub] wrote {', '.join(a.path for a in artifacts)}")
        return artifacts


def _sample_cross_domain_files(ctx: AgentContext) -> list[ArtifactOut]:
    """Small, valid cross-domain catalogue/decision files, so the catalogue flow works end to end without AI: one
    synchronous query to another domain and one event this domain publishes for it."""
    outputs = ctx.config.get("outputs") or []
    other = next((d for d in sorted(ctx.ownership) if d != ctx.domain), "shared")
    op = ctx.operation.lower()
    query, event = f"{other}.get-{other}-summary", f"{ctx.domain}.{op}-completed"
    files: dict[str, str] = {}
    if "cross-domain.yaml" in outputs:
        files["cross-domain.yaml"] = f"""# [stub] sample cross-domain catalogue
interactions:
  - id: X1
    direction: outbound
    target: {other}
    kind: query
    summary: Reads a {other} summary while handling {ctx.operation}
    code_refs: []
    consistency: immediate
  - id: X2
    direction: inbound
    target: {other}
    kind: side-effect
    summary: {other} reacts after {ctx.operation} completes
    code_refs: []
    consistency: eventual
"""
    if "domain-dependencies.yaml" in outputs:
        files["domain-dependencies.yaml"] = f"""# [stub] sample domain dependencies
feature: {ctx.operation}
domain: {ctx.domain}
decision:
  scope: cross-domain
  reason: "[stub] Reads a {other} summary while handling {ctx.operation}"
dependencies:
  - domain: {other}
    relation: calls
    direction: outbound
    strength: hard
    interactions: [X1]
    touchpoints:
      - kind: service
        ref: com.acme.{other}.{other.capitalize()}Service#get{other.capitalize()}Summary
        owner: {other}
        used_for: Reads a {other} summary while handling {ctx.operation}
        code_refs: []
considered_unrelated: []
shared_code: []
"""
    if "integration-decisions.yaml" in outputs:
        files["integration-decisions.yaml"] = f"""# [stub] sample integration decisions
decisions:
  - interaction: X1
    direction: outbound
    target: {other}
    kind: query
    pattern: sync-api
    contract: {query}
    port: {other.capitalize()}Directory
    adapter: Monolith{other.capitalize()}DirectoryAdapter
    status: planned
    summary: REST call through the monolith facade until {other} is migrated
  - interaction: X2
    direction: inbound
    target: {other}
    kind: side-effect
    pattern: event
    contract: {event}
    status: planned
    summary: Published through the outbox to the {ctx.domain} topic
contracts:
  - key: {query}
    provider: {other}
    kind: api
    name: Get {other} summary
    version: "1"
    consumers: [{ctx.domain}]
    spec: contracts/{query}.yaml
  - key: {event}
    provider: {ctx.domain}
    kind: event
    name: {ctx.operation} completed
    version: "1"
    consumers: [{other}]
    spec: contracts/{event}.yaml
"""
        files[f"contracts/{query}.yaml"] = f"""openapi: 3.1.0
info: {{title: "{other} summary (stub)", version: "1"}}
paths:
  /internal/api/v1/{other}/summary/{{id}}:
    get:
      responses: {{"200": {{description: Summary}}}}
"""
        files[f"contracts/{event}.yaml"] = f"""asyncapi: 3.0.0
info: {{title: "{ctx.operation} completed (stub)", version: "1"}}
channels:
  {ctx.domain}-events:
    messages: {{{op}Completed: {{payload: {{type: object}}}}}}
"""
    written = []
    for name, content in files.items():
        f = ctx.output_dir / name
        f.parent.mkdir(parents=True, exist_ok=True)
        f.write_text(content)
        written.append(ArtifactOut(name=f.name, path=ctx.rel(f), kind="yaml"))
    return written


SAMPLE_CONTEXT = "documents"  # a bounded context the sample discovery "finds" in addition to the known domains


def _sample_discovery_files(ctx: AgentContext) -> list[ArtifactOut]:
    """Small, valid discovery files, so discovery works end to end without AI: the known domains plus one new bounded
    context, and three features for a domain."""
    outputs = ctx.config.get("outputs") or []
    domains = sorted(ctx.ownership)
    files: dict[str, str] = {}
    if "bounded-contexts.yaml" in outputs:
        keys = [*domains, SAMPLE_CONTEXT] if SAMPLE_CONTEXT not in domains else domains
        lines = ["# [stub] sample bounded contexts", "contexts:"]
        for i, key in enumerate(keys):
            ident = key.replace("-", "_")
            depends = f"[{keys[i - 1]}]" if i else "[]"
            lines += [f"  - key: {key}", f"    name: {key.replace('-', ' ').replace('_', ' ').capitalize()}",
                      f"    description: Everything about {key} (sample)",
                      f"    packages: [com.acme.{ident}]", f"    tables: [{ident.upper()}]",
                      f"    entry_points: [src/main/java/com/acme/web/{key.capitalize()}Controller.java]",
                      f"    depends_on: {depends}"]
        files["bounded-contexts.yaml"] = "\n".join(lines) + "\n"
    if "features.yaml" in outputs:
        other = next((d for d in domains if d != ctx.domain), None)
        table = ctx.domain.upper().replace("-", "_")
        lines = ["# [stub] sample features", "features:"]
        controller = f"{ctx.domain.capitalize()}Controller"
        for key, name, calls in ((f"view-{ctx.domain}", f"View {ctx.domain}", []),
                                 (f"create-{ctx.domain}", f"Create {ctx.domain}", [other] if other else []),
                                 (f"close-{ctx.domain}", f"Close {ctx.domain}", [])):
            lines += [f"  - key: {key}", f"    name: {name}", f"    description: {name} (sample)",
                      f"    entry_points: [{controller}.{key.split('-')[0]}, /{ctx.domain}/{key}.do]",
                      f"    tables: [{table}]", f"    calls: [{', '.join(calls)}]"]
        files["features.yaml"] = "\n".join(lines) + "\n"
    written = []
    for name, content in files.items():
        f = ctx.output_dir / name
        f.write_text(content)
        written.append(ArtifactOut(name=f.name, path=ctx.rel(f), kind="yaml"))
    return written
