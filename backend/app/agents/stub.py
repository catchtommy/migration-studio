"""Placeholder agents that exercise the full orchestration (files, commits, artifacts, gates) without an LLM."""

import time

from app.agents.base_agent import AgentContext, ArtifactOut, StageAgent
from app.config import settings
from app.orchestrator.stages import StageDef

STUB_DELAY = 0.5  # seconds per step, so the UI shows stages progressing


class StubAgent(StageAgent):
    def __init__(self, stage: str):
        self.stage = stage

    def run(self, ctx: AgentContext) -> list[ArtifactOut]:
        stage = ctx.stage_def or StageDef(self.stage, self.stage, "agent", ctx.config.get("description", ""))
        ctx.log(f"[stub] {stage.title}: analysing {ctx.domain}/{ctx.operation}")
        time.sleep(STUB_DELAY)
        if ctx.feedback:
            ctx.log(f"[stub] applying reviewer feedback: {ctx.feedback}")
        answer = None
        if settings.stub_questions:
            answer = ctx.ask(f"[stub] Anything {stage.title} should know about {ctx.operation}?",
                             ["Nothing to add", "See the notes on the domain"])

        out = ctx.output_dir / f"{self.stage}.md"
        lines = [
            f"# {stage.title} — {ctx.domain} / {ctx.operation}",
            "",
            f"_Attempt {ctx.attempt}. Generated by the stub agent; switch this agent to Claude on the Agents page._",
            "",
            "## Purpose",
            stage.description,
        ]
        if ctx.previous_artifacts:
            lines += ["", "## Inputs from earlier steps"]
            lines += [f"- {d.stage_title}: `{d.path}`" + (" (contents included)" if d.content is not None else "")
                      for d in ctx.previous_artifacts]
        guidance = ctx.inputs.as_markdown()
        if guidance:
            lines += ["", "## Inputs received", ""]
            lines += ["#" + line if line.startswith("## ") else line for line in guidance.splitlines()]
        if answer is not None:
            lines += ["", "## Answer received", answer]
        if ctx.feedback:
            lines += ["", "## Reviewer feedback addressed", ctx.feedback]
        out.write_text("\n".join(lines) + "\n")
        time.sleep(STUB_DELAY)
        ctx.log(f"[stub] wrote {ctx.rel(out)}")
        return [ArtifactOut(name=out.name, path=ctx.rel(out), kind="markdown")]
